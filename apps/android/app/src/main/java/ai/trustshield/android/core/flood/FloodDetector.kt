package ai.trustshield.android.core.flood

/** Content-free signal retained only for the active grouping window. */
data class FloodEvent(
    val timestampMillis: Long,
    val sourceKey: String,
    val kind: FloodKind,
    val callOutcome: CallOutcome? = null,
    val isOtpLike: Boolean = false
)

enum class FloodKind { SMS, CALL }
enum class CallOutcome { ANSWERED, MISSED, REJECTED }
enum class FloodSeverity { NONE, WATCH, FLOOD }
enum class FloodReason { NONE, SMS_BROAD, SMS_SAME_SENDER, SMS_OTP_SERVICES, CALL_REPEAT, CALL_DISTRIBUTED }
enum class FloodProfile { NORMAL, STRICT }

data class FloodResult(
    val severity: FloodSeverity,
    val count: Int = 0,
    val windowMillis: Long = 0,
    val reason: FloodReason = FloodReason.NONE,
    val plainLanguageReason: String = "No unusual message or call pattern."
)

/**
 * A small in-memory sliding-window detector. No message text is accepted or retained here.
 * The source key should be a short-lived hash generated by the Android adapter.
 */
class FloodDetector(private val profile: FloodProfile = FloodProfile.NORMAL) {
    private val events = ArrayDeque<FloodEvent>()
    private var lastTimestamp = Long.MIN_VALUE

    val retainedEventCount: Int get() = events.size

    fun record(event: FloodEvent): FloodResult {
        // Ignore stale out-of-order deliveries after a wall clock rollback; never rewind the window.
        if (lastTimestamp != Long.MIN_VALUE && event.timestampMillis < lastTimestamp) return evaluate(lastTimestamp)
        lastTimestamp = event.timestampMillis
        events.addLast(event)
        val retention = HOUR
        while (events.isNotEmpty() && events.first().timestampMillis < lastTimestamp - retention) events.removeFirst()
        while (events.size > MAX_EVENTS) events.removeFirst()
        return evaluate(lastTimestamp)
    }

    fun snapshot(nowMillis: Long = if (lastTimestamp == Long.MIN_VALUE) 0 else lastTimestamp): FloodResult =
        evaluate(maxOf(nowMillis, lastTimestamp))

    fun recentEvents(nowMillis: Long = if (lastTimestamp == Long.MIN_VALUE) 0 else lastTimestamp): List<FloodEvent> {
        val now = maxOf(nowMillis, lastTimestamp)
        return events.filter { it.timestampMillis >= now - HOUR }
    }

    fun clear() {
        events.clear()
        lastTimestamp = Long.MIN_VALUE
    }

    private fun evaluate(now: Long): FloodResult {
        val smsBroad = events.filter { it.kind == FloodKind.SMS && it.timestampMillis >= now - MINUTE }
        val smsSame = events.filter { it.kind == FloodKind.SMS && it.timestampMillis >= now - 30_000 }
            .groupBy { it.sourceKey }.values.maxByOrNull { it.size }.orEmpty()
        val otp = events.filter { it.kind == FloodKind.SMS && it.isOtpLike && it.timestampMillis >= now - 2 * MINUTE }
        val otpSources = otp.map { it.sourceKey }.distinct().size
        val recentCalls = events.filter { it.kind == FloodKind.CALL && it.timestampMillis >= now - 5 * MINUTE }
        val repeatCalls = recentCalls.groupBy { it.sourceKey }.values
            .filter { calls ->
                val unanswered = calls.all { it.callOutcome == CallOutcome.MISSED || it.callOutcome == CallOutcome.REJECTED }
                val floodPattern = calls.size >= (if (profile == FloodProfile.NORMAL) 3 else 2) &&
                    calls.dropLast(1).all { it.callOutcome == CallOutcome.MISSED || it.callOutcome == CallOutcome.REJECTED }
                calls.size >= 2 && (unanswered || floodPattern)
            }.maxByOrNull { it.size }.orEmpty()

        val smsBroadFlood = if (profile == FloodProfile.NORMAL) 8 else 6
        val smsSameFlood = if (profile == FloodProfile.NORMAL) 5 else 4
        val smsOtpFlood = if (profile == FloodProfile.NORMAL) 6 else 4
        val smsOtpSources = if (profile == FloodProfile.NORMAL) 3 else 2
        val repeatCallFlood = if (profile == FloodProfile.NORMAL) 3 else 2
        val distributedCallFlood = if (profile == FloodProfile.NORMAL) 4 else 3

        return when {
            smsBroad.size >= smsBroadFlood -> result(FloodSeverity.FLOOD, smsBroad.size, MINUTE, FloodReason.SMS_BROAD,
                "${smsBroad.size} messages arrived within 60 seconds.")
            smsSame.size >= smsSameFlood -> result(FloodSeverity.FLOOD, smsSame.size, 30_000, FloodReason.SMS_SAME_SENDER,
                "${smsSame.size} messages arrived from one sender within 30 seconds.")
            otp.size >= smsOtpFlood && otpSources >= smsOtpSources -> result(FloodSeverity.FLOOD, otp.size, 2 * MINUTE, FloodReason.SMS_OTP_SERVICES,
                "${otp.size} code-like messages arrived from $otpSources services within 2 minutes.")
            repeatCalls.size >= repeatCallFlood -> result(FloodSeverity.FLOOD, repeatCalls.size, 5 * MINUTE, FloodReason.CALL_REPEAT,
                "${repeatCalls.size} missed or rejected calls came from one number within 5 minutes.")
            recentCalls.map { it.sourceKey }.distinct().size >= distributedCallFlood -> result(FloodSeverity.FLOOD, recentCalls.size, 5 * MINUTE, FloodReason.CALL_DISTRIBUTED,
                "${recentCalls.size} calls came from different numbers within 5 minutes.")
            smsBroad.size >= smsBroadFlood - 2 -> result(FloodSeverity.WATCH, smsBroad.size, MINUTE, FloodReason.SMS_BROAD,
                "Message activity is rising: ${smsBroad.size} in 60 seconds.")
            smsSame.size >= smsSameFlood - 1 -> result(FloodSeverity.WATCH, smsSame.size, 30_000, FloodReason.SMS_SAME_SENDER,
                "Several messages arrived from one sender in 30 seconds.")
            otp.size >= smsOtpFlood - 1 && otpSources >= smsOtpSources -> result(FloodSeverity.WATCH, otp.size, 2 * MINUTE, FloodReason.SMS_OTP_SERVICES,
                "Several code-like messages arrived from different services.")
            recentCalls.map { it.sourceKey }.distinct().size >= distributedCallFlood - 1 -> result(FloodSeverity.WATCH, recentCalls.size, 5 * MINUTE, FloodReason.CALL_DISTRIBUTED,
                "Calls are arriving from several different numbers.")
            else -> FloodResult(
                severity = FloodSeverity.NONE,
                count = maxOf(smsBroad.size, smsSame.size, otp.size, recentCalls.size),
                windowMillis = if (recentCalls.isNotEmpty()) 5 * MINUTE else if (smsBroad.isNotEmpty()) MINUTE else 0
            )
        }
    }

    private fun result(severity: FloodSeverity, count: Int, window: Long, reason: FloodReason, copy: String) =
        FloodResult(severity, count, window, reason, copy)

    companion object {
        const val MINUTE = 60_000L
        const val HOUR = 60 * MINUTE
        const val MAX_EVENTS = 256
    }
}

/** Heuristic only; callers must discard [text] immediately and retain just this Boolean. */
fun isOtpLike(text: String): Boolean {
    val normalized = text.lowercase()
    val keyword = listOf("otp", "one time password", "verification code", "security code", "login code", "one-time code")
        .any(normalized::contains)
    val digitCode = Regex("(?<!\\d)\\d{4,8}(?!\\d)").containsMatchIn(normalized)
    return keyword && digitCode || listOf("otp", "verification code", "security code", "login code").any(normalized::contains)
}
